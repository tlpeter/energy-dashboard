window.makeT = function makeT(lang) {
  const dict = window.I18N[lang] || window.I18N.en;
  return (key, vars) => {
    let s = dict[key] ?? window.I18N.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
    return s;
  };
};
